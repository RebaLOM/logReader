        public static IReadOnlyList<HelpTopic> AllTopics { get; } = BuildTopics();

        public static HelpTopic? FindById(string id)
        {
            foreach (var t in AllTopics)
            {
                if (string.Equals(t.Id, id, StringComparison.Ordinal))
                    return t;
            }
            return null;
        }

        public static string GetSearchText(HelpTopic topic)
        {
            var parts = new List<string> { topic.Title };
            foreach (var block in topic.Blocks)
                AppendSearchText(block, parts);
            return string.Join(' ', parts);
        }

        private static void AppendSearchText(HelpBlock block, List<string> parts)
        {
            switch (block)
            {
                case HelpHeading h: parts.Add(h.Text); break;
                case HelpParagraph p: parts.Add(p.Text); break;
                case HelpBullet b: parts.Add(b.Text); break;
                case HelpLabeledItem i: parts.Add(i.Label); parts.Add(i.Text); break;
                case HelpExample e: parts.Add(e.Text); break;
            }
        }

        private static List<HelpTopic> BuildTopics()
        {
            var topics = new List<HelpTopic>();
            topics.AddRange(BuildCoreTopics());
            topics.AddRange(BuildFormatTopics());
            topics.AddRange(BuildEditorTopics());
            topics.AddRange(BuildCompositeTopics());
            topics.AddRange(BuildWorkflowTopics());
            return topics;
        }

